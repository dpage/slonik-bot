// Package output renders the meeting notes as Markdown files.
package output

import (
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"strings"
	"time"

	"github.com/dpage/slonik-bot/internal/summary"
	"github.com/dpage/slonik-bot/internal/transcript"
)

const none = "_None recorded._"

// Dir returns the directory that holds the notes for one meeting.
func Dir(base, code string, started time.Time) string {
	return filepath.Join(base, started.Local().Format("2006-01-02")+"-"+code)
}

// NewDir creates the directory for a new session of a meeting and returns
// its path. If Dir's name is taken, by an earlier session of the same meeting
// on the same day, it adds -2, -3 and so on, so that a session never writes
// over another one's notes. os.Mkdir fails on a directory that exists, so two
// bots starting together cannot both take the same name.
func NewDir(base, code string, started time.Time) (string, error) {
	if err := os.MkdirAll(base, 0o700); err != nil {
		return "", fmt.Errorf("creating %s: %w", base, err)
	}
	first := Dir(base, code, started)
	for n := 1; ; n++ {
		d := first
		if n > 1 {
			d = fmt.Sprintf("%s-%d", first, n)
		}
		err := os.Mkdir(d, 0o700)
		if err == nil {
			return d, nil
		}
		if !errors.Is(err, fs.ErrExist) {
			return "", fmt.Errorf("creating %s: %w", d, err)
		}
	}
}

// escape protects Markdown special characters in text that came from the
// model or from captions, so that a name such as "Bob *Example*" is shown as
// written. Newlines are folded to spaces so a value stays on its line.
func escape(s string) string {
	s = strings.Join(strings.Fields(s), " ")
	var b strings.Builder
	for i, r := range s {
		switch r {
		case '\\', '*', '_', '`', '[', ']', '<', '>':
			b.WriteByte('\\')
		case '#':
			if i == 0 {
				b.WriteByte('\\')
			}
		}
		b.WriteRune(r)
	}
	return b.String()
}

// RenderSummary renders summary.md. The summary text itself is left alone
// because the model writes it as Markdown.
func RenderSummary(m transcript.Meeting, r *summary.Result) string {
	var b strings.Builder
	start, end := m.Started.Local(), m.Ended.Local()
	zone, _ := start.Zone()

	fmt.Fprintf(&b, "# %s\n\n", escape(r.Title))
	fmt.Fprintf(&b, "- **Date:** %s, %s to %s (%s)\n", start.Format("02-01-2006"), start.Format("15:04"), end.Format("15:04"), zone)
	fmt.Fprintf(&b, "- **Meeting:** %s\n", escape(m.Code))
	if len(m.Participants) > 0 {
		names := make([]string, len(m.Participants))
		for i, p := range m.Participants {
			names[i] = escape(p)
		}
		fmt.Fprintf(&b, "- **Participants:** %s\n", strings.Join(names, ", "))
	}

	fmt.Fprintf(&b, "\n## Summary\n\n%s\n\n## Decisions\n\n", strings.TrimSpace(r.Summary))
	if len(r.Decisions) == 0 {
		b.WriteString(none + "\n")
	}
	for _, d := range r.Decisions {
		fmt.Fprintf(&b, "- %s\n", escape(d))
	}

	b.WriteString("\n## Action items\n\n")
	if len(r.ActionItems) == 0 {
		b.WriteString(none + "\n")
	}
	for _, a := range r.ActionItems {
		fmt.Fprintf(&b, "- [ ] %s\n", actionLine(a))
	}

	b.WriteString("\n---\n\n_Generated by slonik-bot from Google Meet's automatic captions, which can mishear. Check anything important against the transcript._\n")
	return b.String()
}

func actionLine(a summary.ActionItem) string {
	var parts []string
	if a.Owner != nil && strings.TrimSpace(*a.Owner) != "" {
		parts = append(parts, escape(*a.Owner))
	} else {
		parts = append(parts, "unassigned")
	}
	if a.Due != nil && strings.TrimSpace(*a.Due) != "" {
		parts = append(parts, "due "+escape(*a.Due))
	}
	return fmt.Sprintf("%s (%s)", escape(a.Description), strings.Join(parts, ", "))
}

// RenderTranscript renders transcript.md, applying corrections to the text.
func RenderTranscript(m transcript.Meeting, us []transcript.Utterance, cs []transcript.Correction) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# Transcript: %s, %s\n\n", escape(m.Code), m.Started.Local().Format("02-01-2006"))
	for _, u := range transcript.Merge(us) {
		off := max(u.Start.Sub(m.Started), 0).Round(time.Second)
		fmt.Fprintf(&b, "**[%02d:%02d:%02d] %s:** %s\n\n",
			int(off.Hours()), int(off.Minutes())%60, int(off.Seconds())%60,
			escape(u.Speaker), escape(transcript.ApplyCorrections(u.Text, cs)))
	}
	return b.String()
}

// WriteFiles writes transcript.md and, when there is a summary, summary.md
// (using its corrections for the transcript). Meeting content is private, so
// the files are readable by the owner only.
func WriteFiles(dir string, m transcript.Meeting, us []transcript.Utterance, r *summary.Result) error {
	if err := os.MkdirAll(dir, 0o700); err != nil {
		return err
	}
	var cs []transcript.Correction
	if r != nil {
		cs = r.Corrections
	}
	if err := os.WriteFile(filepath.Join(dir, "transcript.md"), []byte(RenderTranscript(m, us, cs)), 0o600); err != nil {
		return err
	}
	if r == nil {
		return nil
	}
	return os.WriteFile(filepath.Join(dir, "summary.md"), []byte(RenderSummary(m, r)), 0o600)
}
